import test from 'node:test';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { setPresentedExecutor, beforeToolResolution } from '../src/host/prompt-provider.mjs';
import { executeNativeTool } from '../src/host/native-tool-call.mjs';
const host=createRequire(createRequire(import.meta.url).resolve('@deepseek-ai/dsh/package.json'));
const { Context }=await import(host.resolve('@deepseek-ai/cordis'));
const { ToolRuntime }=await import(host.resolve('@deepseek-ai/dsh-tools'));
const { SystemPrompt }=await import(host.resolve('@deepseek-ai/dsh-system-prompt'));
const { NativeToolExecutor }=await import(host.resolve('@deepseek-ai/dsh-tool-executor-native'));
const { createScope }=await import(host.resolve('@deepseek-ai/dsh-scope'));
const tool=(name,execute)=>({name,description:name,parameters:{type:'object',properties:{}},output:{schema:{type:'string'},render:(_,v)=>[{type:'text',text:v}]},execute});
const call=async(ctx,agent,name,extra={})=>(await ctx.tools.execute({calls:[{type:'tool-call',id:name,name,arguments:'{}'}],agent,signal:new AbortController().signal,...extra})).results[0].result;
test('locked-host providers retain scoped declarations and one admitted tool set through child execution',async t=>{
 const root=new Context();t.after(()=>root.fiber.dispose());await root.plugin(SystemPrompt);await root.plugin(ToolRuntime);
 let owner;await root.inject(['tools','systemPrompt'],ctx=>{owner=ctx});
 const a={},b={};a.ctx=createScope(owner,a).ctx;b.ctx=createScope(owner,b).ctx;
 const original=owner.systemPrompt.assemble;
 setPresentedExecutor(owner,new NativeToolExecutor(owner),(model,_definitions,context)=>({...model,schemas:model.schemas.filter(t=>t.name!==(context.scope===a?'b':'a'))}));
 let admitted=true,prepared=0,calls=0;beforeToolResolution(owner,()=>{prepared++});
 owner.tools.register(tool('a',()=> 'A'));owner.tools.register(tool('b',()=> 'B'));
 owner.tools.register(tool('conditional',()=>{calls++;return 'admitted'}),{when:()=>admitted});
 let parent,child;owner.on('tools/execute',async(exec,next)=>{if(exec.name==='parent')parent=exec;else if(exec.name==='conditional')child=exec;return next()});
 owner.tools.register(tool('parent',async(_,exec)=>{const result=await executeNativeTool(owner,{name:'conditional',arguments:{},callId:'child',rootCallId:exec.rootCallId,parent:exec.token,toolSet:exec.toolSet,agent:exec.agent,signal:exec.signal});return result.isError?'denied':result.value}));
 const signal=new AbortController().signal,selection={provider:'test',model:'test'};
 const sa=await owner.tools.resolve({agent:a,modelSelection:selection,signal}),sb=await owner.tools.resolve({agent:b,modelSelection:selection,signal});
 const [pa,pb]=await Promise.all([owner.systemPrompt.assemble({scope:a,agent:a,toolSet:sa}),owner.systemPrompt.assemble({scope:b,agent:b,toolSet:sb})]);
 assert(!pa.tools.some(t=>t.name==='b'));assert(!pb.tools.some(t=>t.name==='a'));assert.equal(prepared,2);
 assert.equal((await call(owner,a,'parent',{toolSet:sa})).value,'admitted');assert.equal(child.parent,parent.token);assert.equal(child.rootCallId,parent.rootCallId);assert.equal(calls,1);
 admitted=false;const denied=await owner.tools.resolve({agent:a,modelSelection:selection,signal});
 assert.equal((await call(owner,a,'parent',{toolSet:denied})).value,'denied');assert.equal(calls,1);
 sa.dispose();sb.dispose();denied.dispose();assert.equal((await call(owner,a,'conditional',{toolSet:sa})).isError,true);
 assert.notEqual(owner.systemPrompt.assemble,original);
});

test('reviewed Loader-resolved PTC executor exposes only admitted controls and guards stale direct calls',async t=>{
 const { apply }=await import('../src/ptc.mjs');
 let enabled=true;
 const root=new Context();t.after(()=>root.fiber.dispose());await root.plugin(SystemPrompt);await root.plugin(ToolRuntime);
 root.provide('ptcRuntime',{language:'typescript',programFormat:'repl',resolve:spec=>spec,run(){throw Error('Unexpected program dispatch')}});
 root.provide('omd',{prepareBackground(){},backgroundOptions:()=>({interruptibleWait:enabled}),config:()=>({})});
 root.provide('loader',{entries:()=>[{options:{name:'@deepseek-ai/dsh-tools'},parent:{tree:{import:spec=>import(host.resolve(spec))}}}]});
 let injected;await root.inject(['tools','systemPrompt','ptcRuntime','omd','loader'],ctx=>{injected=ctx});
 const preset={},owner=createScope(injected,preset).ctx,agent={};agent.ctx=createScope(owner,agent,{parent:preset}).ctx;
 owner.tools.register(tool('job_output',()=> 'control'));
 owner.tools.register(tool('business',()=> 'business'));
 await apply(owner);
 const context={scope:agent,agent};const first=await owner.systemPrompt.assemble(context);
 assert.deepEqual(first.tools.map(t=>t.name).sort(),['job_output','run_code']);
 assert.equal((await call(owner,agent,'job_output')).value,'control');
 assert.equal((await call(owner,agent,'business')).isError,true);
 enabled=false;const second=await owner.systemPrompt.assemble({scope:agent});assert.deepEqual(second.tools.map(t=>t.name),['run_code']);
 assert.equal((await call(owner,agent,'job_output')).isError,true);
 assert.equal(Object.hasOwn(context,'toolSet'),false);
});
