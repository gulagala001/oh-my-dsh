import { build } from 'esbuild';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Compile the upstream text builders; shims only supply host-owned context or
// unused section metadata. The original TS is kept byte-for-byte alongside them.
export async function promptStyleBuilders() {
  const root = fileURLToPath(new URL('../src/prompt-styles/', import.meta.url));
  const pi = JSON.parse(readFileSync(root + 'upstream/pi/source.json', 'utf8'));
  const docs = `https://github.com/${pi.repo}/blob/${pi.commit}/packages/coding-agent/`;
  const entry = `export { buildSystemPromptSections as piSections } from './upstream/pi/system-prompt.ts';
export { buildIdentitySection as zcodeIdentity } from './upstream/zcode/identity.ts';
export { buildCliPrefixSection as zcodePrefix } from './upstream/zcode/cli-prefix.ts';
export { buildDynamicBehaviorSection as zcodeBehavior, buildContextManagementSection as zcodeContext, buildSessionGuidanceSection as zcodeSession } from './upstream/zcode/dynamic-sections.ts';`;
  const result = await build({ stdin: { contents: entry, resolveDir: root, sourcefile: 'builders-entry.mjs' },
    absWorkingDir: root, bundle: true, write: false, platform: 'node', format: 'esm', target: 'es2022', charset: 'utf8',
    legalComments: 'inline', banner: { js: '// Generated by scripts/check-prompt-styles.mjs --write. See upstream/*/LICENSE and source.json.' },
    plugins: [{ name: 'host-context', setup(b) {
      b.onResolve({ filter: /^(?:@earendil-works\/pi-ai|\.\.\/config\.ts|\.\/skills\.ts|\.\.?\/utils\.js)$/ }, args => ({ path: args.path, namespace: 'host-context' }));
      b.onLoad({ filter: /.*/, namespace: 'host-context' }, ({ path }) => ({ contents:
        path.endsWith('utils.js') ? 'export const estimateTokens = () => 0;'
          : path.endsWith('config.ts') ? `export const getReadmePath = () => ${JSON.stringify(docs + 'README.md')}; export const getDocsPath = () => ${JSON.stringify(docs + 'docs/')}; export const getExamplesPath = () => ${JSON.stringify(docs + 'examples/')};`
          : path.endsWith('skills.ts') ? 'export function formatSkillsForPrompt() { throw Error("Skills belong to the native host assembly"); }'
          : 'export function getSystemMessageText() { throw Error("Transport belongs to the native host assembly"); }', loader: 'js' }));
    } }],
  });
  return result.outputFiles[0].text;
}
